"""Names the entries of the game's typeindex.json: the REP's message type
table. Writes typenames.json (index -> {uuid, name}) next to this script.

    python3 typenames.py path/to/typeindex.json

A type registers itself with its name and its UUID as strings; the name is
the nearest string the code loads before the UUID."""
import json
import re
import sys

import nwre

ti = json.load(open(sys.argv[1]))["typeIndex"]
pat = re.compile(rb"\{?[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}\}?\0")
r = nwre.SECTIONS[".rdata"]
uuid_at = {}
for m in pat.finditer(nwre.data, r[2], r[2] + r[3]):
    s = m.group()[:-1].strip(b"{}").decode().replace("-", "").upper()
    uuid_at[nwre.off2rva(m.start())] = s
wanted = set(ti)
targets = [a for a, u in uuid_at.items() if u in wanted]
refs = nwre.code_refs_many(targets)
UUIDISH = re.compile(r"^\{?[0-9A-Fa-f]{8}-")


def name_before(ref):
    f = nwre.func_of(ref)
    if not f:
        return None
    start = max(f[0], ref - 0x400)
    seen = []
    for a, m, o, sz, t in nwre.disasm_at(start, end=ref):
        if t is None or not (r[0] <= t < r[0] + r[1]):
            continue
        # a long name is loaded in pieces (movups + movsd of its tail): start
        # from the beginning of the string a piece belongs to
        k = 0
        while k < 64 and nwre.read(t - k - 1, 1) not in (bytes(1), b""):
            k += 1
        s = nwre.cstr(t - k, 200)
        if len(s) >= 3 and s.isprintable() and not UUIDISH.match(s) and re.match(r"^[A-Za-z_][\w:<> ,*&]*$", s):
            seen.append((t, s))
    return seen[-1][1] if seen else None


names = {}
for a in targets:
    for ref, _ in refs.get(a, []):
        n = name_before(ref)
        if n:
            names.setdefault(uuid_at[a], n)
            break
out = [{"index": i, "uuid": u, "name": names.get(u, "")} for i, u in enumerate(ti)]
json.dump(out, open(__import__("os").path.join(__import__("os").path.dirname(__file__) or ".", "typenames.json"), "w"), indent=0)
print(f"{len(ti)} types, {sum(1 for o in out if o['name'])} named")
for o in out[:40]:
    print(o["index"], o["uuid"], o["name"])

# rep_types.go: the named entries, for the server's log
go = ["// Code generated by tools/re/typenames.py from the 1.400.6031.6004151",
      "// client's typeindex.json; DO NOT EDIT.", "",
      "package main", "",
      "// repTypeIndex names the entries of the client's type table (typeindex.json)",
      "// that the client registers by name: index -> name.",
      "var repTypeIndex = map[uint32]string{"]
for o in out:
    if o["name"]:
        go.append(f'\t{o["index"]}: "{o["name"]}", // {o["uuid"]}')
go.append("}")
open(__import__("os").path.join(__import__("os").path.dirname(__file__) or ".", "..", "..", "rep_types.go"), "w", newline="\n").write("\n".join(go) + "\n")
